// OAuth resource-server + authorization-server scaffolding
// (docs/plans/oauth-mcp-authentication.md, Phases 1-2): discovery metadata,
// 401 Bearer challenges, and now a real Authorization Code + PKCE + refresh
// token issuer on the new secret-free /mcp and /mcp/<workspace_id> resource
// URLs. OAuth state (authorization codes, access/refresh tokens) lives in
// whichever Durable Object owns the resource — the hub DO for /mcp, the
// per-workspace DO for /mcp/<workspace_id> — resolved via
// resolveOAuthResource() and reached only through internal-only DO routes
// (oauth-authorize/oauth-token/oauth-validate/oauth-mcp/oauth-hub-mcp; see
// BridgeDO.fetch), never exposed at a public URL directly. The JSON-RPC
// handlers remain separate from OAuth routing.
// ---------------------------------------------------------------------------

function oauthResourceUrl(requestUrl, workspaceId) {
  const u = new URL(requestUrl);
  u.pathname = workspaceId ? `/mcp/${workspaceId}` : "/mcp";
  u.search = "";
  u.hash = "";
  return u.toString();
}

function oauthProtectedResourceMetadataUrl(requestUrl, workspaceId) {
  const u = new URL(requestUrl);
  u.pathname = workspaceId ? `/.well-known/oauth-protected-resource/mcp/${workspaceId}` : "/.well-known/oauth-protected-resource/mcp";
  u.search = "";
  u.hash = "";
  return u.toString();
}

function oauthProtectedResourceMetadata(requestUrl, workspaceId) {
  const origin = new URL(requestUrl).origin;
  return {
    resource: oauthResourceUrl(requestUrl, workspaceId),
    authorization_servers: [origin],
  };
}

function oauthAuthorizationServerMetadata(requestUrl) {
  const origin = new URL(requestUrl).origin;
  return {
    issuer: origin,
    authorization_endpoint: `${origin}/oauth/authorize`,
    token_endpoint: `${origin}/oauth/token`,
    registration_endpoint: `${origin}/oauth/register`,
    response_types_supported: ["code"],
    grant_types_supported: ["authorization_code", "refresh_token"],
    code_challenge_methods_supported: ["S256"],
    token_endpoint_auth_methods_supported: ["none"],
    authorization_response_iss_parameter_supported: true,
  };
}

/** Parses an OAuth `resource` parameter (RFC 8707) into the Durable Object
 *  that owns it. Only this Worker's own canonical resource URLs are valid:
 *  "<origin>/mcp" (hub DO) or "<origin>/mcp/<workspace_id>" (that workspace's
 *  DO) — same-origin, no query/fragment, exact path shape. Anything else
 *  (wrong origin, unknown path, trailing slash, etc.) is `invalid_target`. */
function resolveOAuthResource(resourceParam, requestUrl) {
  let resourceUrl;
  try {
    resourceUrl = new URL(resourceParam);
  } catch {
    return { error: "invalid_target" };
  }
  const origin = new URL(requestUrl).origin;
  if (resourceUrl.origin !== origin || resourceUrl.search || resourceUrl.hash) return { error: "invalid_target" };

  const parts = resourceUrl.pathname.split("/").filter(Boolean);
  if (parts.length === 1 && parts[0] === "mcp") {
    return { workspaceId: undefined, resource: `${origin}/mcp`, doName: HUB_DO_NAME };
  }
  if (parts.length === 2 && parts[0] === "mcp" && isValidWorkspaceId(parts[1])) {
    return { workspaceId: parts[1], resource: `${origin}/mcp/${parts[1]}`, doName: parts[1] };
  }
  return { error: "invalid_target" };
}

async function sha256Hex(value) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(value));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

function base64UrlEncode(bytes) {
  let binary = "";
  for (const b of bytes) binary += String.fromCharCode(b);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

/** RFC 7636 S256: BASE64URL(SHA256(ASCII(code_verifier))). */
async function pkceChallengeFromVerifier(verifier) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(verifier));
  return base64UrlEncode(new Uint8Array(digest));
}

function isValidPkceChallenge(challenge) {
  return typeof challenge === "string" && PKCE_CHALLENGE_RE.test(challenge);
}

function isValidPkceVerifier(verifier) {
  return typeof verifier === "string" && PKCE_VERIFIER_RE.test(verifier);
}

/** HTTPS redirect URIs only, except loopback HTTP for local development
 *  clients (localhost / 127.0.0.1 / ::1) — matches common OAuth 2.1 native-app
 *  guidance. No fragment (it would be dropped by user agents anyway and must
 *  not be relied on). Client registration doesn't exist yet in Phase 2, so
 *  the exact string is bound into the authorization code and re-checked
 *  verbatim at token exchange instead of validated against a registry. */
function isValidRedirectUri(uri) {
  let u;
  try {
    u = new URL(uri);
  } catch {
    return false;
  }
  if (u.hash) return false;
  if (u.protocol === "https:") return true;
  if (u.protocol === "http:") return u.hostname === "localhost" || u.hostname === "127.0.0.1" || u.hostname === "::1";
  return false;
}

function normalizeOAuthScope(scope) {
  if (typeof scope !== "string" || scope.trim() === "") return "";
  return scope.trim().split(/\s+/).join(" ");
}

const OAUTH_STATE_MAX_BYTES = 512;
const OAUTH_SCOPE_MAX_BYTES = 1024;
const OAUTH_REDIRECT_URI_MAX_BYTES = 2048;
// RFC 6749 scope-token = 1*NQCHAR, NQCHAR = %x21 / %x23-5B / %x5D-7E
// (any visible ASCII except SP, '"', '\\').
const OAUTH_SCOPE_TOKEN_RE = /^[\x21\x23-\x5B\x5D-\x7E]+$/;

/** `state` is optional and opaque to us — we only bound its size and reject
 *  control characters (CR/LF/NUL in particular, since it's echoed verbatim
 *  into a redirect URL query parameter via URL.searchParams, never string
 *  concatenation, so this isn't an injection vector, but a byte/control-char
 *  cap keeps it from being abused as an arbitrary data channel). */
function isValidOAuthState(state) {
  if (state === null) return true;
  if (typeof state !== "string") return false;
  if (byteLength(state) > OAUTH_STATE_MAX_BYTES) return false;
  for (let i = 0; i < state.length; i++) {
    const code = state.charCodeAt(i);
    if (code <= 0x1f || code === 0x7f) return false;
  }
  return true;
}

/** `scope` is optional (absent/empty means "no scope"). When present, every
 *  space-separated token must be a valid RFC 6749 scope-token — this also
 *  rejects leading/trailing/doubled spaces, since those split into empty
 *  tokens. */
function isValidOAuthScope(scope) {
  if (scope === null || scope === "") return true;
  if (typeof scope !== "string") return false;
  if (byteLength(scope) > OAUTH_SCOPE_MAX_BYTES) return false;
  return scope.split(" ").every((token) => OAUTH_SCOPE_TOKEN_RE.test(token));
}

