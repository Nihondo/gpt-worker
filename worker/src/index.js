    const parsed = await readJsonWithLimit(request, MAX_REQUEST_BYTES);
    if (parsed.tooLarge) return { error: "PAYLOAD_TOO_LARGE" };
    if (parsed.parseError || !parsed.value) return { error: "INVALID_ARGS" };
