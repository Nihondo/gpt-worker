// gpt-worker relay.
//
// One Worker, many workspaces: each workspace gets its own Durable Object
// instance (keyed by workspace_id), so each has an independent queue, its
// own 3 tokens, and its own /link WebSocket — starting the bridge for one
// workspace never evicts another's connection.
//
//   /mcp/<hub_gpt_token>               Shared ChatGPT-facing MCP endpoint. It exposes
//                                       registered workspaces as an explicit tool argument.
//   /mcp/<workspace_id>/<gpt_token>    Legacy per-workspace MCP endpoint (kept for migration).
//   /local/<workspace_id>/<cli_token> CLI-facing postbox API (enqueue / poll / ack / status).
//   /link/<workspace_id>/<link_token> WebSocket reverse-connection from the local bridge process.
//   /admin/<ADMIN_TOKEN>              Provision a new workspace_id, or migrate an old
//                                     single-tenant deployment's tokens into one. Never
//                                     appears in a per-workspace URL; set once machine-wide.
//
// workspace_id is a routing key, not a secret — it just selects which Durable
// Object instance handles the request. The actual gpt/link/cli tokens are
// generated by /admin and stored *inside* that instance's own SQLite (a
// `secrets` table), which is why token validation now happens inside the
// Durable Object rather than here at the top level: only that instance knows
// its own tokens.
//
// The Durable Object (BridgeDO) is the only stateful piece: it holds the message
// queue (SQLite) and the live WebSocket link to the local bridge, using the
// WebSocket Hibernation API so it costs nothing while idle.
//
// See ~/.agents/skills/gpt-worker/SKILL.md for the operating protocol and
// ~/.agents/skills/gpt-worker/reference/protocol.md for message formats.

