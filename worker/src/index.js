// OAuth resource-server + authorization-server scaffolding
// (docs/plans/oauth-mcp-authentication.md, Phases 1-2): discovery metadata,
// 401 Bearer challenges, and now a real Authorization Code + PKCE + refresh
// token issuer on the new secret-free /mcp and /mcp/<workspace_id> resource
// URLs. OAuth state (authorization codes, access/refresh tokens) lives in
// whichever Durable Object owns the resource — the hub DO for /mcp, the
// per-workspace DO for /mcp/<workspace_id> — resolved via
// resolveOAuthResource() and reached only through internal-only DO routes
// (oauth-authorize/oauth-token/oauth-validate/oauth-mcp/oauth-hub-mcp; see
// BridgeDO.fetch), never exposed at a public URL directly. The JSON-RPC
// handlers remain separate from OAuth routing.
