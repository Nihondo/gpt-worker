// ---------------------------------------------------------------------------
// Top-level Worker: validate path shape, then hand off to the right
// per-workspace Durable Object. Per-workspace token validation happens
// *inside* the Durable Object (see BridgeDO.checkToken) — this layer only
// ever sees workspace_id (not secret) and, for /admin, ADMIN_TOKEN.
// ---------------------------------------------------------------------------

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const parts = url.pathname.split("/").filter(Boolean);

    // OAuth discovery metadata is public (no Origin/token gating) and lives
    // outside every other route shape below.
    if (parts[0] === ".well-known") {
      return handleOAuthMetadataRoute(request, parts);
    }

    // OAuth authorization server endpoints advertised by the metadata above.
    if (parts.length === 2 && parts[0] === "oauth" && parts[1] === "authorize") {
      return handleOAuthAuthorizeRoute(request, env);
    }
    if (parts.length === 2 && parts[0] === "oauth" && parts[1] === "token") {
      return handleOAuthTokenRoute(request, env);
    }
    if (parts.length === 2 && parts[0] === "oauth" && parts[1] === "register") {
      return handleOAuthRegisterRoute(request, env);
    }

    // Secret-free OAuth resource URL, shared connector: exactly "/mcp".
    if (parts.length === 1 && parts[0] === "mcp") {
      return handleOAuthMcpResource(request, env, undefined);
    }

    if (parts.length === 2 && parts[0] === "admin") {
      return handleAdminRoute(request, env, parts[1]);
    }

    // OAuth resource URL, per-workspace: "/mcp/<workspace_id>".
    if (parts.length === 2 && parts[0] === "mcp" && isValidWorkspaceId(parts[1])) {
      return handleOAuthMcpResource(request, env, parts[1]);
    }

    if (parts.length !== 3) return new Response("not found", { status: 404 });
    const [route, workspaceId, token] = parts;
    if (!["link", "local"].includes(route)) return new Response("not found", { status: 404 });
    if (!isValidWorkspaceId(workspaceId)) return new Response("not found", { status: 404 });

    if (!checkOrigin(request)) {
      return new Response("forbidden", { status: 403 });
    }

    const doId = env.BRIDGE_DO.idFromName(workspaceId);
    const stub = env.BRIDGE_DO.get(doId);

    // Forward as /<route>/<token> — the Durable Object still needs the
    // token (to check it against its own stored secret), just not the
    // workspace_id (that already *is* which instance it is).
    const forwardUrl = new URL(request.url);
    forwardUrl.pathname = `/${route}/${token}`;
    return stub.fetch(new Request(forwardUrl, request));
  },
};

async function handleAdminRoute(request, env, adminToken) {
  if (!env.ADMIN_TOKEN || !constantTimeEqual(adminToken, env.ADMIN_TOKEN)) {
    return new Response("not found", { status: 404 });
  }
  if (!checkOrigin(request)) return new Response("forbidden", { status: 403 });
  if (request.method !== "POST") return new Response(null, { status: 405, headers: { allow: "POST" } });

  // Peek at workspace_id (size-capped, same as any other body) from a clone
  // so the real body — still fully intact — can be forwarded to the target
  // Durable Object, which reads it again itself.
  const peeked = await readJsonWithLimit(request.clone(), MAX_REQUEST_BYTES);
  if (peeked.tooLarge) return new Response("payload too large", { status: 413 });
  if (peeked.parseError || !peeked.value) return new Response("bad request", { status: 400 });
  if (["provision_hub", "register_workspace", "unregister_workspace", "rotate_hub"].includes(peeked.value.op)) {
    const hub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(HUB_DO_NAME));
    const forwardUrl = new URL(request.url);
    forwardUrl.pathname = "/admin";
    return hub.fetch(new Request(forwardUrl, request));
  }

  const workspaceId = peeked.value.workspace_id;
  if (typeof workspaceId !== "string" || !isValidWorkspaceId(workspaceId)) {
    return new Response("bad request", { status: 400 });
  }

  const doId = env.BRIDGE_DO.idFromName(workspaceId);
  const stub = env.BRIDGE_DO.get(doId);
  const forwardUrl = new URL(request.url);
  forwardUrl.pathname = "/admin";
  return stub.fetch(new Request(forwardUrl, request));
}

function randomHex(bytes) {
  const arr = new Uint8Array(bytes);
  crypto.getRandomValues(arr);
  return [...arr].map((b) => b.toString(16).padStart(2, "0")).join("");
}

function constantTimeEqual(a, b) {
  if (typeof a !== "string" || typeof b !== "string") return false;
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

function checkOrigin(request) {
  const origin = request.headers.get("origin");
  if (!origin) return true; // server-to-server calls (ChatGPT backend, curl, CLI) send none
  return ALLOWED_ORIGINS.has(origin);
}

function checkProtocolVersion(request) {
  const v = request.headers.get("mcp-protocol-version");
  if (!v) return DEFAULT_PROTOCOL_VERSION;
  return PROTOCOL_VERSIONS.has(v) ? v : null;
}

function json(body, status = 200, headers = {}) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json", ...headers },
  });
}

// ---------------------------------------------------------------------------
// OAuth resource-server + authorization-server scaffolding
// (docs/plans/oauth-mcp-authentication.md, Phases 1-2): discovery metadata,
// 401 Bearer challenges, and now a real Authorization Code + PKCE + refresh
// token issuer on the new secret-free /mcp and /mcp/<workspace_id> resource
// URLs. OAuth state (authorization codes, access/refresh tokens) lives in
// whichever Durable Object owns the resource — the hub DO for /mcp, the
// per-workspace DO for /mcp/<workspace_id> — resolved via
// resolveOAuthResource() and reached only through internal-only DO routes
// (oauth-authorize/oauth-token/oauth-validate/oauth-mcp/oauth-hub-mcp; see
// BridgeDO.fetch), never exposed at a public URL directly. The JSON-RPC
// handlers remain separate from OAuth routing.
// ---------------------------------------------------------------------------

function oauthResourceUrl(requestUrl, workspaceId) {
  const u = new URL(requestUrl);
  u.pathname = workspaceId ? `/mcp/${workspaceId}` : "/mcp";
  u.search = "";
  u.hash = "";
  return u.toString();
}

function oauthProtectedResourceMetadataUrl(requestUrl, workspaceId) {
  const u = new URL(requestUrl);
  u.pathname = workspaceId ? `/.well-known/oauth-protected-resource/mcp/${workspaceId}` : "/.well-known/oauth-protected-resource/mcp";
  u.search = "";
  u.hash = "";
  return u.toString();
}

function oauthProtectedResourceMetadata(requestUrl, workspaceId) {
  const origin = new URL(requestUrl).origin;
  return {
    resource: oauthResourceUrl(requestUrl, workspaceId),
    authorization_servers: [origin],
  };
}

function oauthAuthorizationServerMetadata(requestUrl) {
  const origin = new URL(requestUrl).origin;
  return {
    issuer: origin,
    authorization_endpoint: `${origin}/oauth/authorize`,
    token_endpoint: `${origin}/oauth/token`,
    registration_endpoint: `${origin}/oauth/register`,
    response_types_supported: ["code"],
    grant_types_supported: ["authorization_code", "refresh_token"],
    code_challenge_methods_supported: ["S256"],
    token_endpoint_auth_methods_supported: ["none"],
    authorization_response_iss_parameter_supported: true,
  };
}

/** Parses an OAuth `resource` parameter (RFC 8707) into the Durable Object
 *  that owns it. Only this Worker's own canonical resource URLs are valid:
 *  "<origin>/mcp" (hub DO) or "<origin>/mcp/<workspace_id>" (that workspace's
 *  DO) — same-origin, no query/fragment, exact path shape. Anything else
 *  (wrong origin, unknown path, trailing slash, etc.) is `invalid_target`. */
function resolveOAuthResource(resourceParam, requestUrl) {
  let resourceUrl;
  try {
    resourceUrl = new URL(resourceParam);
  } catch {
    return { error: "invalid_target" };
  }
  const origin = new URL(requestUrl).origin;
  if (resourceUrl.origin !== origin || resourceUrl.search || resourceUrl.hash) return { error: "invalid_target" };

  const parts = resourceUrl.pathname.split("/").filter(Boolean);
  if (parts.length === 1 && parts[0] === "mcp") {
    return { workspaceId: undefined, resource: `${origin}/mcp`, doName: HUB_DO_NAME };
  }
  if (parts.length === 2 && parts[0] === "mcp" && isValidWorkspaceId(parts[1])) {
    return { workspaceId: parts[1], resource: `${origin}/mcp/${parts[1]}`, doName: parts[1] };
  }
  return { error: "invalid_target" };
}

async function sha256Hex(value) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(value));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

function base64UrlEncode(bytes) {
  let binary = "";
  for (const b of bytes) binary += String.fromCharCode(b);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

/** RFC 7636 S256: BASE64URL(SHA256(ASCII(code_verifier))). */
async function pkceChallengeFromVerifier(verifier) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(verifier));
  return base64UrlEncode(new Uint8Array(digest));
}

function isValidPkceChallenge(challenge) {
  return typeof challenge === "string" && PKCE_CHALLENGE_RE.test(challenge);
}

function isValidPkceVerifier(verifier) {
  return typeof verifier === "string" && PKCE_VERIFIER_RE.test(verifier);
}

/** HTTPS redirect URIs only, except loopback HTTP for local development
 *  clients (localhost / 127.0.0.1 / ::1) — matches common OAuth 2.1 native-app
 *  guidance. No fragment (it would be dropped by user agents anyway and must
 *  not be relied on). Client registration doesn't exist yet in Phase 2, so
 *  the exact string is bound into the authorization code and re-checked
 *  verbatim at token exchange instead of validated against a registry. */
function isValidRedirectUri(uri) {
  let u;
  try {
    u = new URL(uri);
  } catch {
    return false;
  }
  if (u.hash) return false;
  if (u.protocol === "https:") return true;
  if (u.protocol === "http:") return u.hostname === "localhost" || u.hostname === "127.0.0.1" || u.hostname === "::1";
  return false;
}

function normalizeOAuthScope(scope) {
  if (typeof scope !== "string" || scope.trim() === "") return "";
  return scope.trim().split(/\s+/).join(" ");
}

const OAUTH_STATE_MAX_BYTES = 512;
const OAUTH_SCOPE_MAX_BYTES = 1024;
const OAUTH_REDIRECT_URI_MAX_BYTES = 2048;
// RFC 6749 scope-token = 1*NQCHAR, NQCHAR = %x21 / %x23-5B / %x5D-7E
// (any visible ASCII except SP, '"', '\\').
const OAUTH_SCOPE_TOKEN_RE = /^[\x21\x23-\x5B\x5D-\x7E]+$/;

/** `state` is optional and opaque to us — we only bound its size and reject
 *  control characters (CR/LF/NUL in particular, since it's echoed verbatim
 *  into a redirect URL query parameter via URL.searchParams, never string
 *  concatenation, so this isn't an injection vector, but a byte/control-char
 *  cap keeps it from being abused as an arbitrary data channel). */
function isValidOAuthState(state) {
  if (state === null) return true;
  if (typeof state !== "string") return false;
  if (byteLength(state) > OAUTH_STATE_MAX_BYTES) return false;
  for (let i = 0; i < state.length; i++) {
    const code = state.charCodeAt(i);
    if (code <= 0x1f || code === 0x7f) return false;
  }
  return true;
}

/** `scope` is optional (absent/empty means "no scope"). When present, every
 *  space-separated token must be a valid RFC 6749 scope-token — this also
 *  rejects leading/trailing/doubled spaces, since those split into empty
 *  tokens. */
function isValidOAuthScope(scope) {
  if (scope === null || scope === "") return true;
  if (typeof scope !== "string") return false;
  if (byteLength(scope) > OAUTH_SCOPE_MAX_BYTES) return false;
  return scope.split(" ").every((token) => OAUTH_SCOPE_TOKEN_RE.test(token));
}

function oauthError(error, description, status = 400) {
  const body = description ? { error, error_description: description } : { error };
  return json(body, status, { "cache-control": "no-store" });
}

/** Reads a request body as text under the same streaming size cap as
 *  readJsonWithLimit, without JSON-parsing it — used for OAuth's
 *  application/x-www-form-urlencoded endpoint bodies. */
async function readTextWithLimit(request, maxBytes) {
  const contentLength = request.headers.get("content-length");
  if (contentLength && Number(contentLength) > maxBytes) return { tooLarge: true };

  const reader = request.body ? request.body.getReader() : null;
  if (!reader) return { value: "" };

  let total = 0;
  const chunks = [];
  for (;;) {
    const { done, value } = await reader.read();
    if (done) break;
    total += value.byteLength;
    if (total > maxBytes) {
      try {
        await reader.cancel();
      } catch {
        /* best-effort */
      }
      return { tooLarge: true };
    }
    chunks.push(value);
  }

  const buf = new Uint8Array(total);
  let offset = 0;
  for (const c of chunks) {
    buf.set(c, offset);
    offset += c.byteLength;
  }
  return { value: new TextDecoder().decode(buf) };
}

async function parseOAuthForm(request, maxBytes) {
  const contentType = request.headers.get("content-type") || "";
  if (!contentType.includes("application/x-www-form-urlencoded")) return { unsupportedMediaType: true };
  const read = await readTextWithLimit(request, maxBytes);
  if (read.tooLarge) return { tooLarge: true };
  return { params: new URLSearchParams(read.value) };
}

/** Only a syntactically valid "Bearer <token>" header yields a token.
 *  `attempted` is true whenever an Authorization header was present at all
 *  (well-formed or not), so callers can tell "no credential offered" (no
 *  error param on the 401) apart from "a credential was offered and
 *  rejected" (RFC 6750 error="invalid_token"). */
function extractBearerToken(request) {
  const header = request.headers.get("authorization");
  if (!header) return { token: null, attempted: false };
  const match = /^Bearer\s+(\S+)$/i.exec(header.trim());
  if (!match) return { token: null, attempted: true };
  return { token: match[1], attempted: true };
}

/** Hashes the presented bearer token and asks the DO that owns
 *  `expectedResource` to look it up (internal-only "/oauth-validate" route —
 *  see BridgeDO.handleOAuthValidate). The raw token itself never leaves this
 *  function; only its SHA-256 hash crosses the DO boundary. */
async function validateAccessToken(token, expectedResource, env) {
  const resolved = resolveOAuthResource(expectedResource, expectedResource);
  if (resolved.error) return { valid: false };

  const tokenHash = await sha256Hex(token);
  const stub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(resolved.doName));
  const forwardUrl = new URL(expectedResource);
  forwardUrl.pathname = "/oauth-validate";
  const res = await stub.fetch(
    new Request(forwardUrl, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ tokenHash, resource: expectedResource }),
    }),
  );
  if (res.status !== 200) return { valid: false };
  try {
    return await res.json();
  } catch {
    return { valid: false };
  }
}

function oauthUnauthorized(resourceMetadataUrl, { invalidToken = false } = {}) {
  const params = [`resource_metadata="${resourceMetadataUrl}"`];
  if (invalidToken) params.unshift(`error="invalid_token"`);
  return new Response(null, { status: 401, headers: { "www-authenticate": `Bearer ${params.join(", ")}` } });
}

const HTML_ESCAPES = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
