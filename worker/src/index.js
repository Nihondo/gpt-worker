// ---------------------------------------------------------------------------
// Top-level Worker: validate path shape, then hand off to the right
// per-workspace Durable Object. Per-workspace token validation happens
// *inside* the Durable Object (see BridgeDO.checkToken) — this layer only
// ever sees workspace_id (not secret) and, for /admin, ADMIN_TOKEN.
// ---------------------------------------------------------------------------

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const parts = url.pathname.split("/").filter(Boolean);

    // OAuth discovery metadata is public (no Origin/token gating) and lives
    // outside every other route shape below.
    if (parts[0] === ".well-known") {
      return handleOAuthMetadataRoute(request, parts);
    }

    // OAuth authorization server endpoints advertised by the metadata above.
    if (parts.length === 2 && parts[0] === "oauth" && parts[1] === "authorize") {
      return handleOAuthAuthorizeRoute(request, env);
    }
    if (parts.length === 2 && parts[0] === "oauth" && parts[1] === "token") {
      return handleOAuthTokenRoute(request, env);
    }
    if (parts.length === 2 && parts[0] === "oauth" && parts[1] === "register") {
      return handleOAuthRegisterRoute(request, env);
    }

    // Secret-free OAuth resource URL, shared connector: exactly "/mcp".
    if (parts.length === 1 && parts[0] === "mcp") {
      return handleOAuthMcpResource(request, env, undefined);
    }

    if (parts.length === 2 && parts[0] === "admin") {
      return handleAdminRoute(request, env, parts[1]);
    }

    // OAuth resource URL, per-workspace: "/mcp/<workspace_id>".
    if (parts.length === 2 && parts[0] === "mcp" && isValidWorkspaceId(parts[1])) {
      return handleOAuthMcpResource(request, env, parts[1]);
    }

    // Workspace-owner Web dashboard: "/dashboard/<workspace_id>[/...]"
    // (docs/plans/queue-dashboard.md). This top-level layer only validates
    // workspace_id's shape and forwards — session/login verification happens
    // entirely inside the target DO (see BridgeDO.handleDashboard), same
    // division of responsibility as every other route here.
    if (parts[0] === "dashboard") {
      // Shared hub dashboard: "/dashboard/hub[/...]" — every registered
      // workspace, one owner login (the shared hub_gpt_token). "hub" can
      // never collide with a real workspace_id (isValidWorkspaceId requires
      // 16 hex chars or the legacy "default"), so this check ahead of the
      // per-workspace one below never shadows a real workspace's route.
      // Login/session/CSRF/rate-limit verification happens entirely inside
      // the hub DO (see BridgeDO.handleHubDashboard), same division of
      // responsibility as the per-workspace dashboard.
      if (parts.length >= 2 && parts[1] === "hub") {
        const hub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(HUB_DO_NAME));
        const forwardUrl = new URL(request.url);
        forwardUrl.pathname = `/dashboard/hub${parts.length > 2 ? "/" + parts.slice(2).join("/") : ""}`;
        return hub.fetch(new Request(forwardUrl, request));
      }
      if (parts.length < 2 || !isValidWorkspaceId(parts[1])) return new Response("not found", { status: 404 });
      const workspaceId = parts[1];
      const doId = env.BRIDGE_DO.idFromName(workspaceId);
      const stub = env.BRIDGE_DO.get(doId);
      const forwardUrl = new URL(request.url);
      // workspace_id travels *into* the internal path (unlike /link,/local,
      // which drop it once it has selected the DO instance) because the DO
      // needs it verbatim to scope the session cookie's Path — see
      // dashboardSessionCookie(). It carries no extra authority: the DO
      // instance was already selected by idFromName above, and every
      // dashboard session is validated against that same instance's own
      // dashboard_sessions table regardless of what this segment says.
      forwardUrl.pathname = `/dashboard/${workspaceId}${parts.length > 2 ? "/" + parts.slice(2).join("/") : ""}`;
      return stub.fetch(new Request(forwardUrl, request));
    }

    if (parts.length !== 3) return new Response("not found", { status: 404 });
    const [route, workspaceId, token] = parts;
    if (!["link", "local"].includes(route)) return new Response("not found", { status: 404 });
    if (!isValidWorkspaceId(workspaceId)) return new Response("not found", { status: 404 });

    if (!checkOrigin(request)) {
      return new Response("forbidden", { status: 403 });
    }

    const doId = env.BRIDGE_DO.idFromName(workspaceId);
    const stub = env.BRIDGE_DO.get(doId);

    // Forward as /<route>/<token> — the Durable Object still needs the
    // token (to check it against its own stored secret), just not the
    // workspace_id (that already *is* which instance it is).
    const forwardUrl = new URL(request.url);
    forwardUrl.pathname = `/${route}/${token}`;
    return stub.fetch(new Request(forwardUrl, request));
  },
};

async function handleAdminRoute(request, env, adminToken) {
  if (!env.ADMIN_TOKEN || !constantTimeEqual(adminToken, env.ADMIN_TOKEN)) {
    return new Response("not found", { status: 404 });
  }
  if (!checkOrigin(request)) return new Response("forbidden", { status: 403 });
  if (request.method !== "POST") return new Response(null, { status: 405, headers: { allow: "POST" } });

  // Peek at workspace_id (size-capped, same as any other body) from a clone
  // so the real body — still fully intact — can be forwarded to the target
  // Durable Object, which reads it again itself.
  const peeked = await readJsonWithLimit(request.clone(), MAX_REQUEST_BYTES);
  if (peeked.tooLarge) return new Response("payload too large", { status: 413 });
  if (peeked.parseError || !peeked.value) return new Response("bad request", { status: 400 });
  if (
    [
      "provision_hub",
      "register_workspace",
      "unregister_workspace",
      "rotate_hub",
      "hub_browser_settings_get",
      "hub_browser_settings_set",
      "hub_owner_token_get",
    ].includes(peeked.value.op)
  ) {
    const hub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(HUB_DO_NAME));
    const forwardUrl = new URL(request.url);
    forwardUrl.pathname = "/admin";
    return hub.fetch(new Request(forwardUrl, request));
  }

  const workspaceId = peeked.value.workspace_id;
  if (typeof workspaceId !== "string" || !isValidWorkspaceId(workspaceId)) {
    return new Response("bad request", { status: 400 });
  }

  const doId = env.BRIDGE_DO.idFromName(workspaceId);
  const stub = env.BRIDGE_DO.get(doId);
  const forwardUrl = new URL(request.url);
  forwardUrl.pathname = "/admin";
  return stub.fetch(new Request(forwardUrl, request));
}

