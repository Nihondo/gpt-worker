/** Handles the secret-free OAuth MCP resource routes ("/mcp" and
 *  "/mcp/<workspace_id>"): Bearer-authenticates the request against the
 *  owning DO's issued access tokens, then forwards the original request
 *  (still unread here — its JSON-RPC body is parsed DO-side) into that DO's
 *  internal oauth-mcp/oauth-hub-mcp route, which reuses the existing
 *  handleMcpRequest/handleHubMcpRequest JSON-RPC handlers unchanged. */
async function handleOAuthMcpResource(request, env, workspaceId) {
  if (request.method !== "POST") return new Response(null, { status: 405, headers: { allow: "POST" } });
  if (!checkOrigin(request)) return new Response("forbidden", { status: 403 });

  const metadataUrl = oauthProtectedResourceMetadataUrl(request.url, workspaceId);
  const { token, attempted } = extractBearerToken(request);
  if (!token) return oauthUnauthorized(metadataUrl, { invalidToken: attempted });

  const resource = oauthResourceUrl(request.url, workspaceId);
  const result = await validateAccessToken(token, resource, env);
  if (!result.valid) return oauthUnauthorized(metadataUrl, { invalidToken: true });

  const doName = workspaceId ? workspaceId : HUB_DO_NAME;
  const stub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(doName));
  const forwardUrl = new URL(request.url);
  forwardUrl.pathname = workspaceId ? "/oauth-mcp" : "/oauth-hub-mcp";
  return stub.fetch(new Request(forwardUrl, request));
}

/** GET/POST /oauth/authorize, POST /oauth/token, POST /oauth/register: pick
 *  `resource` from the query string (GET) or a cloned body (POST — same
 *  pattern as handleAdminRoute) to pick the owning DO, then forward the
 *  original, still-unread request into it. Credentials (owner_token / codes
 *  / refresh tokens) travel only in a POST body, never in the URL these
 *  functions build; GET /oauth/authorize itself carries no credential (see
 *  BridgeDO.renderOAuthAuthorizeForm). */
async function handleOAuthAuthorizeRoute(request, env) {
  if (request.method !== "GET" && request.method !== "POST") {
    return new Response(null, { status: 405, headers: { allow: "GET, POST" } });
  }
  // No Origin/Referer check here, unlike the other OAuth/MCP routes: this
  // endpoint has no ambient credential for a cross-site page to ride along
  // on (no cookie/session — owner_token only ever travels because the user
  // typed it into this page's own form), so Origin gating adds no real CSRF
  // protection, only false positives. Real browsers are inconsistent about
  // what Origin (if any — including the literal string "null") they send on
  // this same-origin form POST, which is exactly what broke it before.

  let resourceParam = "";
  if (request.method === "GET") {
    resourceParam = new URL(request.url).searchParams.get("resource") || "";
  } else {
    const parsed = await parseOAuthForm(request.clone(), MAX_REQUEST_BYTES);
    if (parsed.tooLarge) return oauthError("invalid_request", "payload too large", 413);
    if (parsed.unsupportedMediaType) return oauthError("invalid_request", "expected application/x-www-form-urlencoded", 415);
    resourceParam = parsed.params.get("resource") || "";
  }

  const resolved = resolveOAuthResource(resourceParam, request.url);
  if (resolved.error) return oauthError(resolved.error, "resource must be this server's /mcp or /mcp/<workspace_id>", 400);
  const stub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(resolved.doName));
  const forwardUrl = new URL(request.url);
  forwardUrl.pathname = "/oauth-authorize";
  return stub.fetch(new Request(forwardUrl, request));
}

async function handleOAuthTokenRoute(request, env) {
  if (request.method !== "POST") return new Response(null, { status: 405, headers: { allow: "POST" } });
  // No Origin check — same reasoning as handleOAuthAuthorizeRoute. The
  // credential here is `code`+`code_verifier` (PKCE) or a refresh token,
  // never a cookie/session, so there's no ambient authority for Origin
  // gating to protect against. A real OAuth client's token exchange can
  // legitimately come from any origin (its own backend, a browser context
  // on a domain we can't enumerate in advance) — Origin-checking this route
  // only produces false-positive 403s, not real protection.
  const parsed = await parseOAuthForm(request.clone(), MAX_REQUEST_BYTES);
  if (parsed.tooLarge) return oauthError("invalid_request", "payload too large", 413);
  if (parsed.unsupportedMediaType) return oauthError("invalid_request", "expected application/x-www-form-urlencoded", 415);
  const resolved = resolveOAuthResource(parsed.params.get("resource") || "", request.url);
  if (resolved.error) return oauthError(resolved.error, "resource must be this server's /mcp or /mcp/<workspace_id>", 400);
  const stub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(resolved.doName));
  const forwardUrl = new URL(request.url);
  forwardUrl.pathname = "/oauth-token";
  return stub.fetch(new Request(forwardUrl, request));
}

/** RFC 7591-style Dynamic Client Registration. Unlike every other OAuth
 *  route here, this is NOT resource-scoped: a real DCR client (ChatGPT, the
 *  MCP SDK) POSTs plain client metadata with no `resource` field, so this
 *  can't route by resource like handleOAuthAuthorizeRoute/handleOAuthTokenRoute
 *  do. Client records are instead kept globally in the hub DO — every
 *  registration goes there regardless of which resource(s) the client will
 *  later request, and any resource-owning DO looks a client_id up from the
 *  hub via BridgeDO.getOAuthClient() (see there for why). */
async function handleOAuthRegisterRoute(request, env) {
  if (request.method !== "POST") return new Response(null, { status: 405, headers: { allow: "POST" } });
  // No Origin check — DCR is, by design, meant to be callable by any OAuth
  // client software from anywhere (that's the point of *dynamic*
  // registration); there's no ambient credential here at all, so Origin
  // gating would only ever produce false positives, never real protection.
  const stub = env.BRIDGE_DO.get(env.BRIDGE_DO.idFromName(HUB_DO_NAME));
  const forwardUrl = new URL(request.url);
  forwardUrl.pathname = "/oauth-register";
  return stub.fetch(new Request(forwardUrl, request));
}

/** Serves RFC 9728 Protected Resource Metadata and OAuth Authorization
 *  Server Metadata under /.well-known/. Public: no Origin/token gating. */
function handleOAuthMetadataRoute(request, parts) {
  if (request.method !== "GET") return new Response(null, { status: 405, headers: { allow: "GET" } });

  const [, kind, ...rest] = parts;
  if (kind === "oauth-protected-resource") {
    if (rest.length === 0) return json(oauthProtectedResourceMetadata(request.url));
    if (rest.length === 1 && rest[0] === "mcp") return json(oauthProtectedResourceMetadata(request.url));
    if (rest.length === 2 && rest[0] === "mcp") {
      const workspaceId = rest[1];
      if (!isValidWorkspaceId(workspaceId)) return new Response("not found", { status: 404 });
      return json(oauthProtectedResourceMetadata(request.url, workspaceId));
    }
    return new Response("not found", { status: 404 });
  }
  if (kind === "oauth-authorization-server" && rest.length === 0) {
    return json(oauthAuthorizationServerMetadata(request.url));
  }
  return new Response("not found", { status: 404 });
}

